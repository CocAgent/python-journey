"""Show arithmetic operators before variables are introduced."""

print("2 + 3 =", 2 + 3)
print("10 - 4 =", 10 - 4)
print("6 * 7 =", 6 * 7)

# Chia thường luôn trả về float, kể cả khi chia hết.
print("10 / 2 =", 10 / 2)

# Chia lấy phần nguyên và phần dư đi theo cặp.
print("10 // 3 =", 10 // 3)
print("10 % 3 =", 10 % 3)

print("2 ** 10 =", 2**10)
